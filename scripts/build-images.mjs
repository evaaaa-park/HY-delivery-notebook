// Builds the app's image assets from local source photos:
//   - product photos (background-removed PNGs) -> public/products/<productId>.webp (trimmed, 256px, ~10-30KB)
//   - app icons from assets/brand/hy-logo.png  -> public/icons/*
//   - src/generated/product-photos.js (which products have a photo)
//
// Sources stay on the developer's machine (gitignored): hyFredit_누끼_80개/ and product-images-found/cutout/.
// A computer without them keeps the photos already built in public/products/ (they are in git).
// To add or replace one photo: save a background-removed PNG as product-images-found/cutout/<productId>.png.
// Run: npm run images
