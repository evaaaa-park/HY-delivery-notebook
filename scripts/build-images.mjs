const nfc = s => s.normalize('NFC')

async function listDir(dir) {
  if (!existsSync(dir)) return new Map()
  const names = await readdir(dir)
  return new Map(names.map(n => [nfc(n), path.join(dir, n)]))
}

async function productWebp(src, out) {
  // trim transparent margins, fit in 256x256 keeping transparency
  const trimmed = await sharp(src).ensureAlpha().trim({ threshold: 4 }).toBuffer()
  await sharp(trimmed)
    .resize(256, 256, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .webp({ quality: 84, alphaQuality: 90, effort: 6 })
    .toFile(out)
}

async function buildProducts() {
  await mkdir(OUT_PRODUCTS, { recursive: true })
  const main = await listDir(SRC_MAIN)
  const found = await listDir(SRC_FOUND)
  const done = {}
  for (const [id, file] of Object.entries(MAIN)) {
    const src = main.get(nfc(file))
    if (!src) continue // not on this machine: the built photo is kept below
    await productWebp(src, path.join(OUT_PRODUCTS, `${id}.webp`))
    done[id] = 'hyFredit'
  }
  // photos found later (background-removed into product-images-found/cutout/<id>.png)
  for (const [name, src] of found) {
    const m = name.match(/^([a-z0-9_]+)\.png$/i)
    if (!m || done[m[1]]) continue
    await productWebp(src, path.join(OUT_PRODUCTS, `${m[1]}.webp`))
    done[m[1]] = 'found'
  }
  // keep every photo that is already built but has no source here, with the source it was built from
  let before = {}
  try { before = (await import(pathToFileURL(OUT_LIST).href)).PHOTO_SOURCE || {} } catch { /* first run */ }
  const kept = []
  for (const name of await readdir(OUT_PRODUCTS)) {
    const m = name.match(/^([a-z0-9_]+)\.webp$/i)
    if (!m || done[m[1]]) continue
    done[m[1]] = before[m[1]] || 'found'
    kept.push(m[1])
  }
  const ids = Object.keys(done).sort()
  const sources = Object.fromEntries(ids.map(id => [id, done[id]]))
  const body = `// Generated by scripts/build-images.mjs. Product ids that have a photo in public/products/.\n` +
    `export const PRODUCT_PHOTOS = new Set(${JSON.stringify(ids)})\n` +
    `// where each photo came from: 'hyFredit' (scraped, background removed) or 'found' (found later, check)\n` +
    `export const PHOTO_SOURCE = ${JSON.stringify(sources, null, 2)}\n`
  await mkdir(path.dirname(OUT_LIST), { recursive: true })
  await writeFile(OUT_LIST, body)
  console.log(`product photos: ${ids.length} (${ids.join(', ')})`)
  if (kept.length) console.log(`kept as built (source not on this machine): ${kept.join(', ')}`)
  const missing = (await import('../src/domain/constants.js')).DEFAULT_PRODUCTS.map(p => p.id).filter(id => !done[id])
  if (missing.length) console.warn(`no photo yet: ${missing.join(', ')}`)
}

async function buildIcons() {
  await mkdir(OUT_ICONS, { recursive: true })
  // logo cut out of its white/transparent canvas
  const flat = await sharp(LOGO).flatten({ background: '#ffffff' }).toBuffer()
  const trimmed = await sharp(flat).trim({ background: '#ffffff', threshold: 10 }).toBuffer()
  const white = { r: 255, g: 255, b: 255, alpha: 1 }
  const square = async (size, scale, out, round = 0) => {
    const inner = Math.round(size * scale)
    const logo = await sharp(trimmed).resize(inner, inner, { fit: 'contain', background: white }).toBuffer()
    let img = sharp({ create: { width: size, height: size, channels: 4, background: white } }).composite([{ input: logo, gravity: 'center' }])
    if (round) {
      const mask = Buffer.from(`<svg width="${size}" height="${size}"><rect width="${size}" height="${size}" rx="${round}" ry="${round}"/></svg>`)
      img = sharp(await img.png().toBuffer()).composite([{ input: mask, blend: 'dest-in' }])
    }
    await img.png({ compressionLevel: 9 }).toFile(path.join(OUT_ICONS, out))
  }
  await square(512, 0.62, 'icon-512.png')
  await square(192, 0.62, 'icon-192.png')
  await square(512, 0.5, 'icon-maskable-512.png') // content inside the 80% safe zone
  await square(180, 0.64, 'apple-touch-icon.png') // iOS: opaque, iOS rounds the corners itself
  await square(64, 0.74, 'favicon-64.png', 14)
  await square(256, 0.66, 'logo-256.png', 56) // in-app logo (header, sign-in)
  console.log('icons: icon-192, icon-512, icon-maskable-512, apple-touch-icon, favicon-64, logo-256')
}

